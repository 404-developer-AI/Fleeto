    [Fact]
    public void A_debian_version_splits_into_epoch_upstream_and_revision()
    {
        Assert.Equal((1L, "8.9p1", "3ubuntu0.10"), PackageVersions.SplitDpkg("1:8.9p1-3ubuntu0.10"));
        Assert.Equal((0L, "1.2-3", "5"), PackageVersions.SplitDpkg("1.2-3-5"));
        Assert.Equal((0L, "1.0", ""), PackageVersions.SplitDpkg("1.0"));
        Assert.Equal((7L, "1-a:b", "5"), PackageVersions.SplitDpkg("7:1-a:b-5"));
    }
